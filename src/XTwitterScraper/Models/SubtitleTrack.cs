[JsonConverter(typeof(JsonModelConverter<SubtitleTrack, SubtitleTrackFromRaw>))]
public sealed record class SubtitleTrack : JsonModel
{
    /// <summary>
    /// Media key of the video, as media rows carry it.
    /// </summary>
    public string? MediaKey
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNullableClass<string>("mediaKey");
        }
        init
        {
            if (value == null)
            {
                return;
            }

            this._rawData.Set("mediaKey", value);
        }
    }

    /// <summary>
    /// Language code of the track, in lower case.
    /// </summary>
    public string? Language
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNullableClass<string>("language");
        }
        init
        {
            if (value == null)
            {
                return;
            }

            this._rawData.Set("language", value);
        }
    }

    /// <summary>
    /// Track name the uploader or X gave it.
    /// </summary>
    public string? Name
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNullableClass<string>("name");
        }
        init
        {
            if (value == null)
            {
                return;
            }

            this._rawData.Set("name", value);
        }
    }

    /// <summary>
    /// True when X transcribed the audio itself.
    /// </summary>
    public required bool AutoGenerated
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNotNullStruct<bool>("autoGenerated");
        }
        init { this._rawData.Set("autoGenerated", value); }
    }

    /// <summary>
    /// Link to the track's first WebVTT file.
    /// </summary>
    public required string UrlValue
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNotNullClass<string>("url");
        }
        init { this._rawData.Set("url", value); }
    }

    /// <summary>
    /// Every cue's text in order, as 1 line.
    /// </summary>
    public required string Text
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNotNullClass<string>("text");
        }
        init { this._rawData.Set("text", value); }
    }

    /// <summary>
    /// True when the cues cover only the start of a very long track.
    /// </summary>
    public required bool Truncated
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNotNullStruct<bool>("truncated");
        }
        init { this._rawData.Set("truncated", value); }
    }

    /// <summary>
    /// Timed captions in order.
    /// </summary>
    public required IReadOnlyList<SubtitleTrackCues> Cues
    {
        get
        {
            this._rawData.Freeze();
            return this._rawData.GetNotNullStruct<ImmutableArray<SubtitleTrackCues>>("cues");
        }
        init
        {
            this._rawData.Set<ImmutableArray<SubtitleTrackCues>>(
                "cues",
                ImmutableArray.ToImmutableArray(value)
            );
        }
    }

    /// <inheritdoc/>
    public override void Validate()
    {
        _ = this.MediaKey;
        _ = this.Language;
        _ = this.Name;
        _ = this.AutoGenerated;
        _ = this.UrlValue;
        _ = this.Text;
        _ = this.Truncated;
        foreach (var item in this.Cues)
        {
            item.Validate();
        }
    }

    public SubtitleTrack() { }

